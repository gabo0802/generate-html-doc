"""Build a sanitizer-proof static HTML doc (works in Obsidian's HTML viewer and similar).

usage: python build.py SRC.html [-o OUT.html] [--spec SPEC.json] [--theme NAME]

Steps: apply the theme (assets/themes/NAME.css, from --theme or <meta name="doc-theme">) -> fill
<!--src:*--> excerpts (if a spec exists) -> render <pre class="filetree"> blocks -> bake syntax
highlighting into <pre><code class="lang-X"> blocks -> convert inline <svg> to data-URI <img>, resolving
var(--token) from the theme -> strip scripts and on* handlers -> structural checks. SRC "name.src.html" defaults to OUT "name.html"; otherwise in place.
Spec defaults to "<name>.snippets.json" next to SRC.
"""
import argparse
import base64
import html
import os
import re
import sys
import xml.etree.ElementTree as ET
from html.parser import HTMLParser

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from hl import highlight  # noqa: E402
import snippets  # noqa: E402

THEMES = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "assets", "themes")
VOID = {"area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta", "source", "track", "wbr"}
XML_ENT = {"amp", "lt", "gt", "quot", "apos"}
warnings = []


def theme_names():
    return sorted(f[:-4] for f in os.listdir(THEMES) if f.endswith(".css")) if os.path.isdir(THEMES) else []


def apply_theme(doc, name):
    """Swap the /*theme:start ... /*theme:end*/ region of the page CSS for assets/themes/<name>.css."""
    meta = re.search(r'<meta\s+name="doc-theme"\s+content="([\w-]*)"\s*/?>', doc)
    name = name or (meta.group(1) if meta else "")
    if not name or name == "custom":
        return doc, name or "custom"
    path = os.path.join(THEMES, name + ".css")
    if not os.path.isfile(path):
        raise SystemExit(f"unknown theme {name!r}; available: {', '.join(theme_names())}, custom")
    m = re.search(r"/\*theme:start.*?/\*theme:end\*/", doc, re.S)
    if not m:
        raise SystemExit("doc names a theme but its <style> has no /*theme:start ... /*theme:end*/ region (see the template)")
    with open(path, encoding="utf-8") as f:
        css = f.read().strip()
    block = "/*theme:start - " + name + " (from assets/themes; regenerated by build.py) */\n" + css + "\n/*theme:end*/"
    doc = doc[:m.start()] + block + doc[m.end():]
    tag = f'<meta name="doc-theme" content="{name}">'
    doc = doc.replace(meta.group(0), tag) if meta else re.sub(r"(<meta charset[^>]*>)", r"\1\n" + tag, doc, count=1)
    return doc, name


def theme_tokens(doc):
    """(light, dark) dicts of --token values, from the page's :root{} and :root[data-theme="dark"]{} blocks."""
    css = "".join(re.findall(r"<style\b[^>]*>(.*?)</style>", re.sub(r"<svg\b.*?</svg>", "", doc, flags=re.S), re.S))
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)

    def collect(sel):
        out = {}
        for body in re.findall(sel + r"\s*\{([^{}]*)\}", css):
            for k, v in re.findall(r"--([\w-]+)\s*:\s*([^;]+)", body):
                out[k] = v.strip()
        return out
    light = collect(r":root")
    dark = dict(light)
    dark.update(collect(r':root\[data-theme="dark"\]'))
    return light, dark


def resolve_vars(text, tokens, missing):
    def sub(m):
        if m.group(1) in tokens:
            return tokens[m.group(1)]
        missing.add(m.group(1))
        return m.group(2) or "currentColor"
    for _ in range(3):  # tokens that reference tokens
        text = re.sub(r"var\(\s*--([\w-]+)\s*(?:,\s*([^()]*))?\)", sub, text)
    return text


FT_STATUS = {"new", "mod", "del", "ren"}


def render_filetrees(doc):
    """<pre class="filetree" data-groups="key=Label; ..."> indented lines -> legend + tree table.

    Line: INDENT NAME [new|mod|del|ren] [@group] [# description]. Children inherit a directory's group."""
    count = 0

    def sub(m):
        nonlocal count
        count += 1
        attrs, body = m.group(1), html.unescape(re.sub(r"<[^>]+>", "", m.group(2)))
        gm = re.search(r'data-groups="([^"]*)"', attrs)
        groups = {}
        for part in (gm.group(1).split(";") if gm else []):
            if "=" in part:
                k, label = part.split("=", 1)
                groups[k.strip()] = (f"g{len(groups) % 6 + 1}", label.strip())
        nodes, stack = [], []  # stack of (indent, node)
        for raw in body.splitlines():
            if not raw.strip():
                continue
            indent = len(raw) - len(raw.lstrip())
            line, _, desc = raw.strip().partition(" #")
            if line.startswith("#"):
                line, desc = "", line[1:]
            toks = line.split()
            status = group = None
            while toks and (toks[-1] in FT_STATUS or toks[-1].startswith("@")):
                t = toks.pop()
                if t.startswith("@"):
                    group = t[1:]
                else:
                    status = t
            name = " ".join(toks)
            while stack and stack[-1][0] >= indent:
                stack.pop()
            parent = stack[-1][1] if stack else None
            if group and group not in groups:
                warnings.append(f"filetree: @{group} is not in data-groups")
                groups[group] = (f"g{len(groups) % 6 + 1}", group)
            node = {"name": name, "status": status, "desc": desc.strip(), "kids": [],
                    "group": group or (parent["group"] if parent else None)}
            (parent["kids"] if parent else nodes).append(node)
            stack.append((indent, node))
        rows = []

        def walk(items, prefix, top):
            for i, n in enumerate(items):
                last = i == len(items) - 1
                guide = "" if top else prefix + ("└── " if last else "├── ")
                cls = ["ft-name"] + ([groups[n["group"]][0]] if n["group"] else []) \
                    + (["ft-dir"] if n["name"].endswith("/") or n["kids"] else []) + (["ft-del"] if n["status"] == "del" else [])
                badge = f'<span class="ft-badge {n["status"]}">{n["status"]}</span>' if n["status"] else ""
                rows.append(f'<tr><td class="ft-path"><span class="ft-guide">{guide}</span>'
                            f'<span class="{" ".join(cls)}">{html.escape(n["name"])}</span></td>'
                            f'<td class="ft-st">{badge}</td><td class="ft-desc">{html.escape(n["desc"])}</td></tr>')
                walk(n["kids"], "" if top else prefix + ("    " if last else "│   "), False)
        walk(nodes, "", True)
        legend = "".join(f'<span class="ft-key {c}">{html.escape(label)}</span>' for c, label in groups.values())
        return ('<div class="ftree">' + (f'<div class="ft-legend">{legend}</div>' if legend else "")
                + '<table class="ft">' + "".join(rows) + "</table></div>")
    doc = re.sub(r'<pre\b([^>]*\bclass="filetree"[^>]*)>(.*?)</pre>', sub, doc, flags=re.S)
    return doc, count


def bake_code(doc):
    def sub(m):
        text = html.unescape(re.sub(r"<[^>]+>", "", m.group(3)))
        return m.group(1) + highlight(text, m.group(2)) + "</code>"
    doc, n = re.subn(r'(<code\b[^>]*\bclass="(?:lang|language)-([\w+#-]+)"[^>]*>)(.*?)</code>', sub, doc, flags=re.S)
    doc = re.sub(r'<pre(?![^>]*\bdata-lang=)([^>]*)>(\s*<code\b[^>]*\bclass="(?:lang|language)-([\w+#-]+)")',
                 r'<pre data-lang="\3"\1>\2', doc)
    return doc, n


def svg_to_img(doc):
    light, dark = theme_tokens(doc)
    missing = set()

    def themed_style(m):
        css = re.sub(r"/\*.*?\*/", "", m.group(2), flags=re.S)
        if "var(" not in css:
            return m.group(0)
        if "@media" in css:
            return m.group(1) + resolve_vars(css, light, missing) + m.group(3)
        out = resolve_vars(css, light, missing).rstrip()
        dk = resolve_vars(css, dark, missing).strip()
        if dk != out.strip():
            out += "\n@media (prefers-color-scheme:dark){" + dk + "}\n"
        return m.group(1) + out + m.group(3)

    def sub(m):
        svg = m.group(0)
        svg = re.sub(r"(<style\b[^>]*>)(.*?)(</style>)", themed_style, svg, flags=re.S)
        svg = resolve_vars(svg, light, missing)
        open_tag = re.match(r"<svg\b[^>]*>", svg).group(0)
        vb = re.search(r'viewBox="\s*[-\d.]+[\s,]+[-\d.]+[\s,]+([\d.]+)[\s,]+([\d.]+)\s*"', open_tag)
        if not vb:
            raise SystemExit("inline <svg> without viewBox=\"0 0 W H\": " + open_tag[:120])
        w, h = (str(round(float(x))) for x in vb.groups())
        style = re.search(r'\bstyle="([^"]*)"', open_tag)
        label = re.search(r'\baria-label="([^"]*)"', open_tag) or re.search(r"<title>(.*?)</title>", svg, re.S)
        tag = open_tag
        for attr in ("width", "height", "style", "class", "xmlns"):
            tag = re.sub(rf'\s{attr}="[^"]*"', "", tag)
        font = light.get("font-body", "Segoe UI, system-ui, sans-serif").replace('"', "'")
        extra = "" if "font-family=" in tag else f' font-family="{html.escape(font)}"'
        tag = tag[:-1] + f' xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}"{extra}>'
        svg = tag + svg[len(open_tag):]
        svg = re.sub(r"&(\w+);", lambda e: e.group(0) if e.group(1) in XML_ENT else f"&#{ord(html.unescape(e.group(0))[0])};", svg)
        if re.search(r'\sclass="', svg) and "<style" not in svg:
            warnings.append("svg uses class= but has no internal <style>; page CSS does NOT reach data-URI images")
        try:
            ET.fromstring(svg)
        except ET.ParseError as e:
            raise SystemExit(f"svg is not well-formed XML ({e}): {svg[:160]}")
        b64 = base64.b64encode(svg.encode("utf-8")).decode()
        alt = html.escape(label.group(1).strip() if label else "diagram")
        st = f"display:block;width:100%;max-width:{w}px;height:auto;" + (style.group(1) if style else "margin:8px 0")
        return f'<img class="diagram" alt="{alt}" style="{st}" src="data:image/svg+xml;base64,{b64}">'
    n = len(re.findall(r"<svg\b", doc))
    doc = re.sub(r"<svg\b.*?</svg>", sub, doc, flags=re.S)
    if missing:
        warnings.append("svg uses undefined tokens: " + ", ".join("--" + t for t in sorted(missing)))
    return doc, n


def strip_unsafe(doc):
    doc, ns = re.subn(r"\s*<script\b.*?</script>", "", doc, flags=re.S | re.I)
    nh = 0
    handler = re.compile(r'(<[a-zA-Z][^<>]*?)\son[a-z]+=(?:"[^"]*"|\'[^\']*\')', re.I)
    while True:
        doc, k = handler.subn(r"\1", doc)
        if not k:
            break
        nh += k
    if ns or nh:
        warnings.append(f"removed {ns} <script> and {nh} on* handlers (they do not run in sanitized viewers)")
    return doc


class Balance(HTMLParser):
    def __init__(self):
        super().__init__()
        self.stack, self.errors = [], []

    def handle_starttag(self, tag, attrs):
        if tag not in VOID:
            self.stack.append((tag, self.getpos()[0]))

    def handle_endtag(self, tag):
        if tag in VOID:
            return
        if self.stack and self.stack[-1][0] == tag:
            self.stack.pop()
        else:
            self.errors.append(f"line {self.getpos()[0]}: </{tag}> but open is {self.stack[-1] if self.stack else None}")


def check(doc):
    b = Balance()
    b.feed(doc)
    errors = b.errors[:10] + [f"unclosed <{t}> from line {ln}" for t, ln in b.stack[:10]]
    # The contents rail may be sticky: where a viewer does not honour it, the rail is a plain column that scrolls away.
    unrailed = re.sub(r"nav\.toc\s*\{[^}]*\}", "", doc)
    if re.search(r"position\s*:\s*(fixed|sticky)", unrailed, re.I):
        warnings.append("found position:fixed/sticky outside nav.toc (sanitized viewers often clip it)")
    page_css = "".join(re.findall(r"<style\b[^>]*>(.*?)</style>", re.sub(r"<svg\b.*?</svg>", "", doc, flags=re.S), re.S))
    if re.search(r"<[/\w!]", page_css):
        errors.append("page <style> contains '<' followed by a letter, '/' or '!' (e.g. a tag named in a comment); "
                      "DOMPurify then drops the whole stylesheet")
    for pat, msg in [
                     (r"@import|<link\b[^>]*stylesheet", "external stylesheet (blocked offline / by viewers)"),
                     (r"url\(\s*['\"]?https?:", "remote url() in CSS"), (r"<iframe\b", "<iframe>"),
                     (r":target\b", ":target selector (unreliable without real anchors)"),
                     (r'<img\b[^>]*src="https?:', "remote image")]:
        if re.search(pat, doc, re.I):
            warnings.append("found " + msg)
    return errors


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("src")
    ap.add_argument("-o", "--out")
    ap.add_argument("--spec")
    ap.add_argument("--theme", help="theme from assets/themes (overrides <meta name=\"doc-theme\">), or 'custom'")
    a = ap.parse_args()
    src = os.path.abspath(a.src)
    stem = re.sub(r"(\.src)?\.html?$", "", src, flags=re.I)
    out = a.out or (stem + ".html" if src.lower().endswith(".src.html") else src)
    spec = a.spec or stem + ".snippets.json"
    with open(src, encoding="utf-8") as f:
        doc = f.read()

    doc, theme = apply_theme(doc, a.theme)
    report = {}
    if os.path.exists(spec):
        doc, report = snippets.fill(doc, spec)
    elif re.search(r"<!--src:", doc):
        raise SystemExit(f"doc has <!--src:--> markers but no spec at {spec}")
    doc, n_tree = render_filetrees(doc)
    doc, n_code = bake_code(doc)
    doc, n_svg = svg_to_img(doc)
    doc = strip_unsafe(doc)
    errors = check(doc)

    with open(out, "w", encoding="utf-8", newline="") as f:
        f.write(doc)
    print(f"wrote {out} ({len(doc.encode()) // 1024} KB)")
    print(f"theme {theme} | file trees {n_tree} | code blocks {n_code} | svgs->img {n_svg} | excerpt groups {report.get('filled', 0)}"
          + (f" | unused spec groups {report['unused_groups']}" if report.get("unused_groups") else ""))
    for w in dict.fromkeys(warnings):
        print("WARN", w)
    for e in errors:
        print("ERROR", e)
    sys.exit(1 if errors else 0)


if __name__ == "__main__":
    main()
